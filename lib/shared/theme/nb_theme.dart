import 'package:flutter/material.dart';

import 'nb_colors.dart';

/// Familias tipográficas bundleadas (ver `pubspec.yaml`).
abstract final class NbFonts {
  /// Titulares y cifras destacadas.
  static const String display = 'SpaceGrotesk';

  /// Texto de interfaz.
  static const String ui = 'Manrope';
}

/// Definición de un tema NB Sound: clave estable (espejo del PC, para
/// persistencia), nombre legible, brillo (derivado del fondo) y paleta [NbColors].
@immutable
class NbThemeDef {
  const NbThemeDef({
    required this.key,
    required this.label,
    required this.brightness,
    required this.colors,
  });

  /// Clave estable (snake_case, espejo del escritorio) usada al persistir.
  final String key;

  /// Nombre legible para la UI de selección de tema.
  final String label;

  /// Claridad de la paleta (afecta ColorScheme y overlays del sistema). Se deriva
  /// de la luminancia del fondo en [_def].
  final Brightness brightness;

  /// Paleta de tokens resuelta.
  final NbColors colors;
}

/// Construye una [NbColors] desde los tokens del escritorio, derivando
/// line/line2 del borde y soft/ambient/ink del acento.
NbColors _buildColors({
  required int fondo,
  required int fondoElevado,
  required int superficieAlt,
  required int borde,
  required int texto,
  required int textoSec,
  required int textoMuted,
  required int acento,
  required int acentoFuerte,
}) {
  final Color accent = Color(acento);
  final Color bordeC = Color(borde);
  // Tinta legible sobre el acento según su luminancia.
  final Color ink = accent.computeLuminance() > 0.55
      ? const Color(0xFF0A0A0A)
      : const Color(0xFFFFFFFF);
  return NbColors(
    bg: Color(fondo),
    bg2: Color(fondoElevado),
    bg3: Color(superficieAlt),
    line: bordeC.withValues(alpha: 0.5),
    line2: bordeC,
    text: Color(texto),
    text2: Color(textoSec),
    text3: Color(textoMuted),
    accent: accent,
    accent2: Color(acentoFuerte),
    ink: ink,
    soft: accent.withValues(alpha: 0.14),
    ambient: accent.withValues(alpha: 0.22),
  );
}

/// Crea una definición de tema, derivando el brillo de la luminancia del fondo
/// (claro si la luminancia > 0.5).
NbThemeDef _def(
  String key,
  String label, {
  required int fondo,
  required int fondoElevado,
  required int superficieAlt,
  required int borde,
  required int texto,
  required int textoSec,
  required int textoMuted,
  required int acento,
  required int acentoFuerte,
}) {
  final Brightness brightness =
      Color(fondo).computeLuminance() > 0.5 ? Brightness.light : Brightness.dark;
  return NbThemeDef(
    key: key,
    label: label,
    brightness: brightness,
    colors: _buildColors(
      fondo: fondo,
      fondoElevado: fondoElevado,
      superficieAlt: superficieAlt,
      borde: borde,
      texto: texto,
      textoSec: textoSec,
      textoMuted: textoMuted,
      acento: acento,
      acentoFuerte: acentoFuerte,
    ),
  );
}


final Map<String, NbThemeDef> _porKey = <String, NbThemeDef>{
  for (final NbThemeDef t in kNbThemes) t.key: t,
};

/// Resuelve una clave de tema persistida. Acepta las claves antiguas camelCase de
/// los 6 temas originales (compatibilidad con instalaciones previas). Respaldo al
/// primer tema del catálogo.
String nbThemeKeyFromStored(String? v) {
  if (v != null && _porKey.containsKey(v)) {
    return v;
  }
  const Map<String, String> legacy = <String, String>{
    'negroPuro': 'negro_puro',
    'arcillaNocturna': 'arcilla_nocturna',
    'hieloOled': 'hielo_oled',
    'arcillaCalida': 'arcilla_calida',
    'blancoEditorial': 'blanco_editorial',
    'marfilGrafito': 'marfil_grafito',
  };
  final String? m = legacy[v];
  if (m != null && _porKey.containsKey(m)) {
    return m;
  }
  return kNbThemes.first.key;
}

/// Definición de un tema por su clave (respaldo al primero).
NbThemeDef nbThemeByKey(String key) => _porKey[key] ?? kNbThemes.first;

/// Construye el [ThemeData] de la app a partir de la clave de tema [key].
abstract final class NbTheme {
  static ThemeData build(String key) {
    final NbThemeDef def = nbThemeByKey(key);
    final NbColors c = def.colors;
    final Brightness brightness = def.brightness;
    final ColorScheme scheme = ColorScheme.fromSeed(
      seedColor: c.accent,
      brightness: brightness,
      surface: c.bg,
      onSurface: c.text,
      primary: c.accent,
      onPrimary: c.ink,
    );

    return ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: scheme,
      scaffoldBackgroundColor: c.bg,
      canvasColor: c.bg,
      fontFamily: NbFonts.ui,
      splashFactory: InkSparkle.splashFactory,
      extensions: <ThemeExtension<dynamic>>[c],
      textTheme: _textTheme(c),
      iconTheme: IconThemeData(color: c.text, size: 22),
      dividerColor: c.line,
    );
  }

  static TextTheme _textTheme(NbColors c) {
    TextStyle display(double size, FontWeight w) => TextStyle(
          fontFamily: NbFonts.display,
          fontSize: size,
          fontWeight: w,
          letterSpacing: -0.02 * size,
          color: c.text,
          height: 1.1,
        );
    TextStyle ui(double size, FontWeight w, Color color) => TextStyle(
          fontFamily: NbFonts.ui,
          fontSize: size,
          fontWeight: w,
          color: color,
        );

    return TextTheme(
      displaySmall: display(24, FontWeight.w800),
      headlineMedium: display(22, FontWeight.w800),
      headlineSmall: display(19, FontWeight.w800),
      titleLarge: display(18, FontWeight.w700),
      titleMedium: ui(15, FontWeight.w600, c.text),
      titleSmall: ui(13.5, FontWeight.w600, c.text),
      bodyLarge: ui(15, FontWeight.w500, c.text),
      bodyMedium: ui(13.5, FontWeight.w500, c.text2),
      bodySmall: ui(12.5, FontWeight.w500, c.text3),
      labelLarge: ui(13.5, FontWeight.w600, c.text),
      labelMedium: ui(12, FontWeight.w600, c.text2),
      labelSmall: ui(11, FontWeight.w600, c.text3),
    );
  }
}
